# ============================================
# STREAMLIT DASHBOARD - PREDIKSI SHOPEE + SHAP
# ============================================
import streamlit as st
import pandas as pd
import numpy as np
import joblib
import json
import matplotlib.pyplot as plt
from sklearn.preprocessing import LabelEncoder
import shap
import traceback
import warnings
warnings.filterwarnings('ignore')

# ============================================
# 1. SETUP HALAMAN
# ============================================
st.set_page_config(
    page_title="Prediksi Pembatalan Shopee",
    page_icon="🛍️",
    layout="wide"
)

st.title("🛍️ PREDIKSI PEMBATALAN PESANAN SHOPEE")
st.markdown("**Upload data transaksi untuk memprediksi pesanan berisiko Batal**")
st.markdown("---")

# ============================================
# 2. LOAD MODEL
# ============================================
@st.cache_resource
def load_model():
    try:
        model = joblib.load('random_forest_model.pkl')
        scaler = joblib.load('scaler.pkl')
        with open('feature_cols.json', 'r') as f:
            feature_cols = json.load(f)
        return model, scaler, feature_cols
    except Exception as e:
        st.error(f"❌ Error loading model: {e}")
        st.info("Pastikan file berikut ada di folder yang sama:")
        st.code("""
        1. random_forest_model.pkl
        2. scaler.pkl
        3. feature_cols.json
        """)
        return None, None, None

model, scaler, feature_cols = load_model()

if model is None:
    st.stop()

# ============================================
# 3. UPLOAD FILE
# ============================================
st.subheader("📂 UPLOAD FILE TRANSAKSI")

uploaded_file = st.file_uploader(
    "Upload file CSV atau Excel dari Shopee Seller Center",
    type=['csv', 'xlsx'],
    help="File dari Shopee Seller Center dengan kolom: Metode Pembayaran, Opsi Pengiriman, Total Pembayaran, dll."
)

if uploaded_file is not None:
    # Baca file
    try:
        if uploaded_file.name.endswith('.csv'):
            df = pd.read_csv(uploaded_file)
        else:
            df = pd.read_excel(uploaded_file)

        st.success(f"✅ File berhasil diupload! {len(df)} transaksi ditemukan.")

        # Tampilkan data
        with st.expander("📋 Lihat Data"):
            st.dataframe(df.head(20))

        # ============================================
        # 4. PREDIKSI
        # ============================================
        if st.button("🚀 Prediksi Sekarang", type="primary"):

            try:
                df_pred = df.copy()

                # ============================================
                # FEATURE ENGINEERING
                # ============================================

                # 4a. Temporal Features
                if 'Waktu Pesanan Dibuat' in df_pred.columns:
                    df_pred['Waktu Pesanan Dibuat'] = pd.to_datetime(df_pred['Waktu Pesanan Dibuat'])
                    df_pred['month'] = df_pred['Waktu Pesanan Dibuat'].dt.month
                    df_pred['day'] = df_pred['Waktu Pesanan Dibuat'].dt.day
                    df_pred['hour'] = df_pred['Waktu Pesanan Dibuat'].dt.hour
                    df_pred['day_of_week'] = df_pred['Waktu Pesanan Dibuat'].dt.dayofweek
                else:
                    st.warning("⚠️ Kolom 'Waktu Pesanan Dibuat' tidak ditemukan, menggunakan default.")
                    df_pred['month'] = 1
                    df_pred['day'] = 1
                    df_pred['hour'] = 0
                    df_pred['day_of_week'] = 0

                # 4b. Encoding fitur kategorikal
                le = LabelEncoder()
                encoders = {}

                if 'Metode Pembayaran' in df_pred.columns:
                    df_pred['payment_method_enc'] = le.fit_transform(df_pred['Metode Pembayaran'].astype(str))
                    encoders['Metode Pembayaran'] = le
                else:
                    st.error("❌ Kolom 'Metode Pembayaran' tidak ditemukan!")
                    st.info("Pastikan file memiliki kolom: Metode Pembayaran, Opsi Pengiriman, Username (Pembeli), Kota/Kabupaten")
                    st.stop()

                if 'Opsi Pengiriman' in df_pred.columns:
                    le = LabelEncoder()
                    df_pred['shipping_option_enc'] = le.fit_transform(df_pred['Opsi Pengiriman'].astype(str))
                    encoders['Opsi Pengiriman'] = le
                else:
                    st.error("❌ Kolom 'Opsi Pengiriman' tidak ditemukan!")
                    st.stop()

                if 'Username (Pembeli)' in df_pred.columns:
                    le = LabelEncoder()
                    df_pred['username_enc'] = le.fit_transform(df_pred['Username (Pembeli)'].astype(str))
                    encoders['Username (Pembeli)'] = le
                else:
                    st.error("❌ Kolom 'Username (Pembeli)' tidak ditemukan!")
                    st.stop()

                if 'Kota/Kabupaten' in df_pred.columns:
                    le = LabelEncoder()
                    df_pred['city_enc'] = le.fit_transform(df_pred['Kota/Kabupaten'].astype(str))
                    encoders['Kota/Kabupaten'] = le
                else:
                    st.error("❌ Kolom 'Kota/Kabupaten' tidak ditemukan!")
                    st.stop()

                # 4c. Pastikan semua fitur yang dibutuhkan ada
                missing_cols = [col for col in feature_cols if col not in df_pred.columns]
                if missing_cols:
                    st.error(f"❌ Kolom tidak ditemukan: {missing_cols}")
                    st.info("Pastikan file CSV memiliki semua kolom yang dibutuhkan model.")
                    st.stop()

                # 4d. Ambil fitur dan prediksi
                X = df_pred[feature_cols]

                # Standarisasi
                X_scaled = scaler.transform(X)

                # Prediksi
                predictions = model.predict(X_scaled)
                probabilities = model.predict_proba(X_scaled)[:, 1]

                # Tambahkan ke dataframe
                df_pred['Status Prediksi'] = ['✅ Selesai' if p == 1 else '❌ Batal' for p in predictions]
                df_pred['Probabilitas Batal'] = probabilities * 100

                st.balloons()

                # ============================================
                # 5. REKAP HASIL
                # ============================================
                st.markdown("---")
                st.subheader("📊 REKAP HASIL PREDIKSI")

                col1, col2, col3, col4 = st.columns(4)
                col1.metric("Total Pesanan", len(df_pred))
                col2.metric("✅ Selesai", sum(predictions == 1))
                col3.metric("❌ Batal", sum(predictions == 0))

                # SEMUA pesanan batal dianggap berisiko
                risiko = sum(predictions == 0)
                col4.metric("⚠️ Berisiko Batal", f"{risiko} pesanan")

                # ============================================
                # 6. PESANAN BERISIKO BATAL
                # ============================================
                st.subheader("⚠️ PESANAN BERISIKO BATAL")

                # Ambil SEMUA pesanan batal
                df_risiko = df_pred[predictions == 0]

                if len(df_risiko) > 0:
                    st.warning(f"⚠️ {len(df_risiko)} pesanan diprediksi BATAL! Periksa detail di bawah.")
                    st.dataframe(df_risiko[['No. Pesanan', 'Total Pembayaran', 'Total Diskon', 'Probabilitas Batal']].head(10))

                    st.info("💡 **TINDAKAN YANG DISARANKAN:**")
                    st.markdown("""
                    1. **Hubungi pembeli** untuk konfirmasi pesanan
                    2. **Berikan diskon kecil** (Rp 15.001 - Rp 20.000) untuk mendorong konversi
                    3. **Pastikan metode pembayaran** tersedia dengan baik
                    """)

                    # ============================================
                    # ⭐ SHAP ANALYSIS - FINAL FIXED (NO WARNING)
                    # ============================================
                    st.markdown("---")
                    st.subheader("🔍 ANALISIS ALASAN PREDIKSI (SHAP)")

                    # Ambil 1 data berisiko batal (yang pertama)
                    contoh_data = df_risiko.iloc[0]
                    nomor_pesanan = contoh_data.get('No. Pesanan', 'Tidak diketahui')

                    st.info(f"📌 **Analisis untuk pesanan #{nomor_pesanan}** (diprediksi BATAL dengan probabilitas {contoh_data['Probabilitas Batal']:.1f}%)")

                    try:
                        # Siapkan input
                        input_data = np.array([contoh_data[feature_cols].values])
                        input_scaled = scaler.transform(input_data)

                        with st.spinner("⏳ Menghitung SHAP values..."):
                            # Buat explainer
                            explainer = shap.TreeExplainer(model)

                            # Hitung SHAP
                            shap_values = explainer.shap_values(input_scaled)

                            # Ambil shap untuk kelas Selesai
                            if isinstance(shap_values, list):
                                shap_plot = shap_values[1]
                            else:
                                shap_plot = shap_values

                            # Ambil expected value untuk kelas Selesai
                            if isinstance(explainer.expected_value, list):
                                expected_val = explainer.expected_value[1]
                            else:
                                expected_val = explainer.expected_value

                            # ⭐ FIX: Pastikan shap_plot adalah 1D
                            if shap_plot.ndim > 1:
                                shap_plot = shap_plot.flatten()

                            # ⭐ FIX: Pastikan expected_val adalah float
                            if isinstance(expected_val, (list, np.ndarray)):
                                expected_val = float(expected_val[0]) if len(expected_val) > 0 else 0.0
                            else:
                                expected_val = float(expected_val)

                            # ⭐ FIX: Pastikan data adalah 1D
                            if input_scaled.ndim > 1:
                                data_1d = input_scaled[0]
                            else:
                                data_1d = input_scaled

                            # ⭐ FIX: Ambil feature_names dari model
                            if hasattr(model, 'feature_names_in_'):
                                model_features = list(model.feature_names_in_)
                            else:
                                model_features = feature_cols

                            # ⭐ FIX: Pastikan shap_plot length = feature length
                            if len(shap_plot) != len(model_features):
                                if len(shap_plot) > len(model_features):
                                    shap_plot = shap_plot[:len(model_features)]
                                else:
                                    shap_plot = np.pad(shap_plot, (0, len(model_features) - len(shap_plot)), 'constant')

                            # ⭐ FIX: Pastikan data_1d length = feature length
                            if len(data_1d) != len(model_features):
                                if len(data_1d) > len(model_features):
                                    data_1d = data_1d[:len(model_features)]
                                else:
                                    data_1d = np.pad(data_1d, (0, len(model_features) - len(data_1d)), 'constant')

                        # 1. Waterfall Plot
                        st.markdown("**📊 Visualisasi Kontribusi Fitur:**")

                        fig, ax = plt.subplots(figsize=(12, 6))

                        shap.waterfall_plot(
                            shap.Explanation(
                                values=shap_plot,
                                base_values=expected_val,
                                data=data_1d,
                                feature_names=model_features
                            ),
                            show=False
                        )
                        st.pyplot(fig)
                        plt.close()

                        # 2. Tabel Kontribusi
                        st.markdown("**📊 Tabel Kontribusi Tiap Fitur:**")

                        kontribusi = pd.DataFrame({
                            'Fitur': model_features,
                            'Kontribusi': shap_plot
                        }).sort_values('Kontribusi', ascending=False)

                        def color_kontribusi(val):
                            if val < 0:
                                return 'color: red'
                            elif val > 0:
                                return 'color: green'
                            return ''

                        st.dataframe(
                            kontribusi.style.applymap(color_kontribusi, subset=['Kontribusi'])
                            .bar(subset=['Kontribusi'], color=['#ff6b6b', '#51cf66'], align='mid')
                        )

                        # 3. Kesimpulan Alasan
                        st.markdown("**💡 KENAPA PESANAN INI DIPREDIKSI BATAL?**")

                        top_negatif = kontribusi[kontribusi['Kontribusi'] < 0].head(3)
                        top_positif = kontribusi[kontribusi['Kontribusi'] > 0].head(3)

                        if len(top_negatif) > 0:
                            st.markdown("**Faktor-faktor yang MENURUNKAN probabilitas Selesai:**")
                            for _, row in top_negatif.iterrows():
                                st.markdown(f"   • **{row['Fitur']}** → menurunkan **{abs(row['Kontribusi']):.3f}**")
                        else:
                            st.info("Tidak ada faktor negatif yang signifikan.")

                        if len(top_positif) > 0:
                            st.markdown("**Faktor-faktor yang MENINGKATKAN probabilitas Selesai:**")
                            for _, row in top_positif.iterrows():
                                st.markdown(f"   • **{row['Fitur']}** → meningkatkan **{row['Kontribusi']:.3f}**")

                        # 4. Rekomendasi Spesifik
                        st.markdown("**📌 REKOMENDASI UNTUK PESANAN INI:**")

                        rekomendasi = []
                        for _, row in top_negatif.iterrows():
                            fitur = row['Fitur']
                            if 'Total Pembayaran' in str(fitur):
                                rekomendasi.append("💰 **Total Pembayaran terlalu kecil** → naikkan harga")
                            elif 'Total Diskon' in str(fitur) or 'Diskon' in str(fitur):
                                rekomendasi.append("🏷️ **Diskon terlalu besar** → kurangi diskon")
                            elif 'shipping' in str(fitur).lower():
                                rekomendasi.append("📦 **Opsi pengiriman kurang tepat** → pilih ekspedisi lebih cepat")
                            elif 'payment' in str(fitur).lower():
                                rekomendasi.append("💳 **Metode pembayaran kurang efektif** → sediakan opsi lebih populer")
                            elif 'Jumlah' in str(fitur):
                                rekomendasi.append("📦 **Jumlah barang sedikit** → berikan promo bundling")
                            elif 'city' in str(fitur).lower():
                                rekomendasi.append("📍 **Lokasi pengiriman** → periksa ongkir")
                            elif 'hour' in str(fitur).lower() or 'jam' in str(fitur):
                                rekomendasi.append("🕐 **Jam pembelian** → perhatikan waktu rawan batal")
                            elif 'month' in str(fitur).lower() or 'bulan' in str(fitur):
                                rekomendasi.append("📅 **Bulan pembelian** → perhatikan trend musiman")

                        if rekomendasi:
                            for r in rekomendasi:
                                st.markdown(f"   • {r}")
                        else:
                            st.markdown("   • Periksa semua faktor di atas untuk meningkatkan konversi.")

                        st.success("✅ Analisis SHAP selesai!")

                    except Exception as e:
                        st.error(f"❌ Error pada SHAP: {e}")
                        st.code(traceback.format_exc())

                else:
                    st.success("✅ Tidak ada pesanan batal! Semua pesanan diprediksi SELESAI.")

                # ============================================
                # 7. TABEL SEMUA HASIL
                # ============================================
                with st.expander("📋 Lihat Semua Hasil Prediksi"):
                    # Tampilkan dengan format rupiah yang lebih baik
                    display_cols = ['No. Pesanan', 'Status Prediksi', 'Probabilitas Batal', 'Total Pembayaran']
                    st.dataframe(df_pred[display_cols])

                # ============================================
                # 8. DOWNLOAD HASIL
                # ============================================
                csv = df_pred.to_csv(index=False).encode('utf-8')
                st.download_button(
                    label="📥 Download Hasil Prediksi (CSV)",
                    data=csv,
                    file_name="hasil_prediksi_shopee.csv",
                    mime="text/csv"
                )

                # ============================================
                # 9. REKOMENDASI BISNIS OTOMATIS - FIXED
                # ============================================
                st.markdown("---")
                st.subheader("💡 REKOMENDASI BISNIS UNTUK ANDA")

                # ⭐ FIX: Filter data dengan Total Pembayaran > 0
                df_selesai_valid = df_pred[
                    (df_pred['Status Prediksi'] == '✅ Selesai') &
                    (df_pred['Total Pembayaran'] > 1000)
                ]

                df_batal_valid = df_pred[
                    (df_pred['Status Prediksi'] == '❌ Batal') &
                    (df_pred['Total Pembayaran'] > 1000)
                ]

                mean_selesai = df_selesai_valid['Total Pembayaran'].mean() if len(df_selesai_valid) > 0 else 0
                mean_batal = df_batal_valid['Total Pembayaran'].mean() if len(df_batal_valid) > 0 else 0

                # Rekomendasi 1: Harga
                st.markdown("**1. 🌟 STRATEGI HARGA**")

                if mean_selesai > 0:
                    st.success(f"✅ Pesanan SELESAI rata-rata: Rp {int(mean_selesai):,}".replace(',', '.'))

                    if mean_batal > 0:
                        st.warning(f"⚠️ Pesanan BATAL rata-rata: Rp {int(mean_batal):,}".replace(',', '.'))
                        if mean_selesai > mean_batal:
                            selisih = mean_selesai - mean_batal
                            st.markdown(f"💡 **Harga selesai lebih tinggi Rp {int(selisih):,}** dari harga batal. Jaga harga di atas Rp {int(mean_batal):,} agar pembeli serius.".replace(',', '.'))
                        else:
                            st.markdown(f"💡 **Perhatikan:** Harga batal lebih tinggi dari harga selesai. Mungkin ada faktor lain yang mempengaruhi.")
                    else:
                        st.info("ℹ️ Tidak ada data pesanan batal dengan pembayaran valid untuk dibandingkan.")
                else:
                    st.info("ℹ️ Tidak ada data pesanan selesai dengan pembayaran valid.")

                # Tambahan: Jumlah data yang difilter
                if len(df_selesai_valid) < len(df_pred[df_pred['Status Prediksi'] == '✅ Selesai']):
                    st.caption(f"ℹ️ {len(df_pred[df_pred['Status Prediksi'] == '✅ Selesai']) - len(df_selesai_valid)} data selesai dengan Total Pembayaran ≤ Rp 1.000 tidak dihitung.")

                # Rekomendasi 2: Diskon
                st.markdown("**2. 🏷️ STRATEGI DISKON**")
                st.info("💡 **Rekomendasi:** Berikan diskon di rentang **Rp 15.001 - Rp 20.000** untuk hasil maksimal.")
                st.markdown("""
                | Kategori Diskon | % Selesai | Rekomendasi |
                |:---|:---:|:---|
                | Rp 15.001 - 20.000 | 85.0% | ✅ PALING EFEKTIF |
                | Rp 10.001 - 15.000 | 85.0% | ✅ Bagus |
                | Rp 20.001 - 25.000 | 81.4% | ✅ Bagus |
                | Tanpa Diskon | 72.7% | ❌ PALING BERISIKO |
                """)

                # Rekomendasi 3: Metode Pembayaran
                st.markdown("**3. 💳 STRATEGI PEMBAYARAN**")
                if 'Metode Pembayaran' in df_pred.columns:
                    # Hitung metode pembayaran terbaik
                    payment_stats = df_pred[df_pred['Status Prediksi'] == '✅ Selesai']['Metode Pembayaran'].value_counts()
                    if len(payment_stats) > 0:
                        best_payment = payment_stats.index[0]
                        st.success(f"✅ Metode pembayaran paling banyak digunakan pembeli SELESAI: **{best_payment}**")
                    else:
                        st.info("ℹ️ Tidak ada data metode pembayaran.")

                # ============================================
                # 10. VISUALISASI
                # ============================================
                st.markdown("---")
                st.subheader("📈 VISUALISASI HASIL")

                fig, ax = plt.subplots(figsize=(10, 4))
                counts = df_pred['Status Prediksi'].value_counts()
                colors = ['#2ecc71' if 'Selesai' in x else '#e74c3c' for x in counts.index]
                ax.bar(counts.index, counts.values, color=colors, edgecolor='black')
                ax.set_xlabel('Status Prediksi')
                ax.set_ylabel('Jumlah Pesanan')
                ax.set_title('Distribusi Hasil Prediksi')
                for i, v in enumerate(counts.values):
                    ax.text(i, v + 5, str(v), ha='center', fontweight='bold')
                st.pyplot(fig)

            except Exception as e:
                st.error(f"❌ Error: {e}")
                st.code(traceback.format_exc())

    except Exception as e:
        st.error(f"❌ Error membaca file: {e}")
        st.info("Pastikan file yang diupload adalah CSV atau Excel yang valid.")

else:
    st.info("📂 Silakan upload file transaksi Shopee Anda.")
    st.markdown("""
    ### 🛠️ Cara Penggunaan:
    1. **Upload file** CSV/Excel dari Shopee Seller Center
    2. Klik tombol **"Prediksi Sekarang"**
    3. Lihat hasil prediksi pesanan yang berisiko Batal
    4. **Download hasil** prediksi
    5. Dapatkan **rekomendasi bisnis** langsung

    ### 📋 Kolom yang dibutuhkan:
    - `No. Pesanan`
    - `Total Pembayaran`
    - `Total Diskon`
    - `Metode Pembayaran`
    - `Opsi Pengiriman`
    - `Username (Pembeli)`
    - `Kota/Kabupaten`
    - `Waktu Pesanan Dibuat` (opsional)
    """)